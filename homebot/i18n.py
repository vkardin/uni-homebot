def set_lang(code: str) -> str:
    global _lang
    _lang = code if code in LANGS else "ru"
    return _lang


def lang() -> str:
    return _lang


def tr(text: str) -> str:
    if _lang == "ru":
        return text
    pair = _T.get(text)
    return pair[0 if _lang == "en" else 1] if pair else text
