def whats_new(previous: object, current: str) -> str:
    """Текст «что нового» или пустая строка (первый запуск, тот же или неизвестная версия)."""
    if not isinstance(previous, str) or not previous or previous == current:
        return ""
    lines = WHATS_NEW.get(current)
    if not lines:
        return ""
    return "\n\n🆕 <b>Что нового в " + current + "</b>\n" + "\n".join(f"• {line}" for line in lines)
